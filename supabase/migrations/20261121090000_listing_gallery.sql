CREATE TABLE IF NOT EXISTS public.listing_images (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id bigint NOT NULL REFERENCES public.listings(id) ON DELETE CASCADE,
    image_path text,
    image_url text,
    position integer NOT NULL DEFAULT 0,
    is_cover boolean NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS listing_images_listing_position_idx ON public.listing_images (listing_id, position);
ALTER TABLE public.listing_images ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.listing_images FROM anon, authenticated;
GRANT ALL ON TABLE public.listing_images TO service_role;
