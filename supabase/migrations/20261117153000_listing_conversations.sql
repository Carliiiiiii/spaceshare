-- Direct questions about listings are separate from rental requests.
-- This migration is intentionally not applied automatically by the app.

DO $$
DECLARE
    listing_id_type text;
    user_id_type text;
BEGIN
    SELECT format_type(attribute.atttypid, attribute.atttypmod)
      INTO listing_id_type
      FROM pg_attribute AS attribute
     WHERE attribute.attrelid = 'public.listings'::regclass
       AND attribute.attname = 'id'
       AND NOT attribute.attisdropped;

    SELECT format_type(attribute.atttypid, attribute.atttypmod)
      INTO user_id_type
      FROM pg_attribute AS attribute
     WHERE attribute.attrelid = 'public.users'::regclass
       AND attribute.attname = 'id'
       AND NOT attribute.attisdropped;

    IF listing_id_type IS NULL OR user_id_type IS NULL THEN
        RAISE EXCEPTION 'Expected public.listings(id) and public.users(id) before creating listing conversations.';
    END IF;

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS public.listing_conversations (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            listing_id %1$s NOT NULL REFERENCES public.listings(id) ON DELETE CASCADE,
            participant_id %2$s NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
            created_at timestamptz NOT NULL DEFAULT now(),
            UNIQUE (listing_id, participant_id)
        )',
        listing_id_type,
        user_id_type
    );

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS public.listing_conversation_messages (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            conversation_id bigint NOT NULL REFERENCES public.listing_conversations(id) ON DELETE CASCADE,
            sender_id %1$s NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
            message text NOT NULL CHECK (char_length(message) BETWEEN 1 AND 1000),
            sent_at timestamptz NOT NULL DEFAULT now()
        )',
        user_id_type
    );

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS public.listing_conversation_reads (
            conversation_id bigint NOT NULL REFERENCES public.listing_conversations(id) ON DELETE CASCADE,
            user_id %1$s NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
            last_read_message_id bigint NOT NULL DEFAULT 0,
            PRIMARY KEY (conversation_id, user_id)
        )',
        user_id_type
    );
END $$;

CREATE INDEX IF NOT EXISTS listing_conversations_participant_id_idx
    ON public.listing_conversations (participant_id);
CREATE INDEX IF NOT EXISTS listing_conversations_listing_id_idx
    ON public.listing_conversations (listing_id);
CREATE INDEX IF NOT EXISTS listing_conversation_messages_conversation_id_idx
    ON public.listing_conversation_messages (conversation_id, sent_at, id);

-- The Streamlit server performs the participant checks with server-side credentials.
-- Keep direct browser access closed until the application uses Supabase Auth and
-- explicit user-scoped policies.
ALTER TABLE public.listing_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.listing_conversation_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.listing_conversation_reads ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.listing_conversations FROM anon, authenticated;
REVOKE ALL ON TABLE public.listing_conversation_messages FROM anon, authenticated;
REVOKE ALL ON TABLE public.listing_conversation_reads FROM anon, authenticated;

GRANT ALL ON TABLE public.listing_conversations TO service_role;
GRANT ALL ON TABLE public.listing_conversation_messages TO service_role;
GRANT ALL ON TABLE public.listing_conversation_reads TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.listing_conversations_id_seq TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.listing_conversation_messages_id_seq TO service_role;
