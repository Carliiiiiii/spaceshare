CREATE TABLE IF NOT EXISTS public.user_blocks (
    blocker_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    blocked_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (blocker_id, blocked_id),
    CHECK (blocker_id <> blocked_id)
);
CREATE TABLE IF NOT EXISTS public.safety_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    target_type text NOT NULL CHECK (target_type IN ('listing', 'message')),
    target_id bigint NOT NULL,
    reason text NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 500),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS safety_reports_created_idx ON public.safety_reports (created_at DESC);
ALTER TABLE public.user_blocks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.safety_reports ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.user_blocks, public.safety_reports FROM anon, authenticated;
GRANT ALL ON TABLE public.user_blocks, public.safety_reports TO service_role;
